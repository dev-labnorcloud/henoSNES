// Modos de direccionamiento; el comentario indica el token de la tabla de referencia.
enum class AddrMode : std::uint8_t {
    Implied,                      // i
    Accumulator,                  // A
    Immediate,                    // #
    Absolute,                     // a
    AbsoluteX,                    // a,X
    AbsoluteY,                    // a,Y
    AbsoluteLong,                 // al
    AbsoluteLongX,                // al,X
    AbsoluteIndirect,             // (a)
    AbsoluteIndexedIndirect,      // (a,X)
    Direct,                       // d
    DirectX,                      // d,X
    DirectY,                      // d,Y
    DirectIndirect,               // (d)
    DirectIndexedIndirect,        // (d,X)
    DirectIndirectIndexed,        // (d),Y
    DirectIndirectLong,           // [d]
    DirectIndirectLongIndexed,    // [d],Y
    StackRelative,                // d,S
    StackRelativeIndirectIndexed, // (d,S),Y
    Relative,                     // r
    RelativeLong,                 // rl
    Stack,                        // s
    BlockMove,                    // xyc
};

// Tamaño del operando inmediato: M o X dependen del flag homónimo; Fixed8 es
// siempre 1 byte (REP, SEP). None para los modos que no son Immediate.
enum class ImmSize : std::uint8_t {
    None,
    Fixed8,
    M,
    X,
};

struct OpcodeInfo {
    Mnemonic mnemonic;
    AddrMode mode;
    std::uint8_t base_bytes;
    ImmSize imm;
};

