// Longitud total en bytes (opcode incluido) según el estado de M y X
// (m8 / x8 = true: registro de 8 bits).
constexpr std::uint8_t instruction_length(std::uint8_t opcode, bool m8, bool x8) noexcept {
    const OpcodeInfo& info = kOpcodeTable[opcode];
    std::uint8_t length = info.base_bytes;
    if (info.imm == ImmSize::M && !m8) {
        ++length;
    }
    if (info.imm == ImmSize::X && !x8) {
        ++length;
    }
    return length;
}

